SUPPORTED_LANGUAGES = tuple(STRINGS)


def normalize_language(language: str | None) -> str:
    """'de-DE' -> 'de'; unknown languages fall back to English."""
    if not language:
        return DEFAULT_LANGUAGE
    code = language.replace("_", "-").split("-")[0].lower()
    return code if code in STRINGS else DEFAULT_LANGUAGE


class Strings:
    """Text lookup for one language with English fallback."""

    def __init__(self, language: str | None) -> None:
        self.language = normalize_language(language)
        self._s = STRINGS[self.language]

    def __call__(self, key: str, **kwargs: object) -> str:
        text = self._s.get(key, STRINGS[DEFAULT_LANGUAGE][key])
        return text.format(**kwargs) if kwargs else text

    def category(self, category: str) -> str:
        return self(f"cat_{category}")

    @property
    def weekdays(self) -> list[str]:
        return self("weekdays").split(",")
